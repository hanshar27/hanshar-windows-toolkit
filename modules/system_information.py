import queue
import threading

import customtkinter as ctk

from core.activity_log import append_log
from core.ui_style import (
    ACCENT_COLOR,
    ACCENT_PURPLE,
    BORDER_COLOR,
    PANEL_COLOR,
    TEXT_PRIMARY,
    TEXT_SECONDARY,
)
from core.system_information import (
    collect_system_information_reports,
    get_system_information_report_paths,
    get_system_information_reports_dir,
    read_system_information_report,
)


class SystemInformationPanel(ctk.CTkFrame):
    def __init__(self, master):
        super().__init__(master, corner_radius=0)
        self.configure(fg_color="transparent")
        self._results = queue.Queue()
        self._task_running = False

        title = ctk.CTkLabel(
            self,
            text="System Information",
            font=ctk.CTkFont(size=28, weight="bold"),
            text_color=TEXT_PRIMARY,
        )
        title.pack(anchor="w", padx=20, pady=(18, 8))

        subtitle = ctk.CTkLabel(
            self,
            text="Complete Windows reports generated by MSInfo32 and DxDiag",
            font=ctk.CTkFont(size=12),
            text_color=TEXT_SECONDARY,
        )
        subtitle.pack(anchor="w", padx=20, pady=(0, 12))

        actions = ctk.CTkFrame(self, fg_color="transparent")
        actions.pack(fill="x", padx=18, pady=(0, 8))

        self.generate_button = ctk.CTkButton(
            actions,
            text="Generate Full Reports",
            command=self.generate_reports,
            corner_radius=12,
            fg_color=ACCENT_COLOR,
            hover_color="#70A4FF",
        )
        self.generate_button.pack(side="left", padx=(0, 8))

        self.load_button = ctk.CTkButton(
            actions,
            text="Load Saved Reports",
            command=self.load_saved_reports,
            corner_radius=12,
            fg_color=ACCENT_PURPLE,
            hover_color="#C779FF",
        )
        self.load_button.pack(side="left")

        self.status_label = ctk.CTkLabel(
            self,
            text="Reports are saved locally in the reports folder.",
            text_color=TEXT_SECONDARY,
            anchor="w",
        )
        self.status_label.pack(fill="x", padx=20, pady=(0, 8))

        self.tabs = ctk.CTkTabview(
            self,
            fg_color=PANEL_COLOR,
            border_width=1,
            border_color=BORDER_COLOR,
            corner_radius=18,
            segmented_button_selected_color=ACCENT_COLOR,
            segmented_button_selected_hover_color="#70A4FF",
        )
        self.tabs.pack(fill="both", expand=True, padx=18, pady=(0, 20))
        self.report_boxes = {}
        for key, tab_name in (("msinfo32", "MSInfo32"), ("dxdiag", "DxDiag")):
            tab = self.tabs.add(tab_name)
            report_box = ctk.CTkTextbox(tab, wrap="word", corner_radius=16)
            report_box.pack(fill="both", expand=True, padx=6, pady=6)
            report_box.insert(
                "1.0",
                "Select Generate Full Reports to collect the complete report, "
                "or Load Saved Reports to open a previous report.",
            )
            report_box.configure(state="disabled")
            self.report_boxes[key] = report_box

    def generate_reports(self):
        self._start_task("generate")

    def load_saved_reports(self):
        self._start_task("load")

    def _start_task(self, task: str):
        if self._task_running:
            return

        self._task_running = True
        self.generate_button.configure(state="disabled")
        self.load_button.configure(state="disabled")
        if task == "generate":
            self.status_label.configure(
                text="Generating both reports. This may take a few minutes..."
            )
            append_log("system_information_started", "Generating MSInfo32 and DxDiag reports")
        else:
            self.status_label.configure(text="Loading saved reports...")

        threading.Thread(target=self._run_task, args=(task,), daemon=True).start()
        self.after(100, self._check_task_result)

    def _run_task(self, task: str):
        try:
            if task == "generate":
                paths = collect_system_information_reports()
            else:
                paths = get_system_information_report_paths()

            contents = {
                name: read_system_information_report(path)
                for name, path in paths.items()
            }
            self._results.put((task, contents, None))
        except Exception as exc:
            self._results.put((task, None, str(exc)))

    def _check_task_result(self):
        try:
            task, contents, error = self._results.get_nowait()
        except queue.Empty:
            self.after(100, self._check_task_result)
            return

        self._task_running = False
        self.generate_button.configure(state="normal")
        self.load_button.configure(state="normal")
        if error:
            action = "generate" if task == "generate" else "load"
            self.status_label.configure(text=f"Could not {action} reports: {error}")
            append_log("system_information_failed", error)
            return

        for name, content in contents.items():
            report_box = self.report_boxes[name]
            report_box.configure(state="normal")
            report_box.delete("1.0", "end")
            report_box.insert("1.0", content)
            report_box.configure(state="disabled")

        if task == "generate":
            self.status_label.configure(
                text=f"Full reports generated and saved in: {get_system_information_reports_dir()}"
            )
            append_log("system_information_generated", str(get_system_information_reports_dir()))
        else:
            self.status_label.configure(text="Saved reports loaded.")
